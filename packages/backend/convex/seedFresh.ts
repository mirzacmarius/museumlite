/**
 * Create all collections for an organization (called from Node.js action)
 */
export const createAllCollectionsForOrg = internalMutation({
  args: {
    organizationId: v.id("organizations"),
    userId: v.id("users"),
    orgSlug: v.string(),
    prefix: v.string(),
  },
  returns: v.array(v.id("collections")),
  handler: async (ctx, args) => {
    const objects = COLLECTION_DATA[args.orgSlug];
    if (!objects) return [];
    
    const collectionIds: Id<"collections">[] = [];
    
    for (let i = 0; i < objects.length; i++) {
      const obj = objects[i];
      const accessionNumber = `${args.prefix}-2024-${String(i + 1).padStart(3, "0")}`;
      
      const collectionId = await ctx.db.insert("collections", {
        organizationId: args.organizationId,
        accessionNumber,
        title: obj.title,
        creator: obj.creator,
        objectType: obj.objectType,
        objectName: obj.objectName,
        culture: obj.culture,
        period: obj.period,
        dateCreated: obj.dateCreated,
        materials: obj.materials,
        technique: obj.technique,
        dimensions: obj.dimensions,
        dimensionHeight: obj.dimensionHeight,
        dimensionWidth: obj.dimensionWidth,
        dimensionDepth: obj.dimensionDepth,
        dimensionWeight: obj.dimensionWeight,
        dimensionUnit: obj.dimensionUnit,
        description: obj.description,
        condition: obj.condition,
        provenance: obj.provenance,
        inscriptions: obj.inscriptions,
        tags: obj.tags,
        creditLine: obj.creditLine,
        status: "active",
        isPubliclyVisible: true,
        catalogedBy: args.userId,
        catalogedAt: Date.now(),
      });
      
      collectionIds.push(collectionId);
    }
    
    return collectionIds;
  },
});

/**
 * Clear all data from relevant tables
 */
export const clearAllData = internalMutation({
  args: {},
  returns: v.null(),
  handler: async (ctx) => {
    // Tables to clear (in order due to foreign key relationships)
    const tablesToClear = [
      "auditLog",
      "notifications",
      "conditionReports",
      "loanItems",
      "loanDocuments",
      "loans",
      "deaccessions",
      "accessions",
      "mediaFiles",
      "locationHistory",
      "collectionGroupItems",
      "collections",
      "collectionGroups",
      "locations",
      "userOrganizations",
      "rolePermissions",
      "roles",
      "organizations",
      "conservationTreatments",
      "exhibitions",
    ] as const;

    for (const tableName of tablesToClear) {
      try {
        const docs = await ctx.db.query(tableName as any).collect();
        for (const doc of docs) {
          await ctx.db.delete(doc._id);
        }
        console.log(`Cleared ${docs.length} records from ${tableName}`);
      } catch (error) {
        console.log(`Skipping ${tableName}: ${error}`);
      }
    }

    // Clear storage files
    const storageFiles = await ctx.db.system.query("_storage").collect();
    for (const file of storageFiles) {
      await ctx.storage.delete(file._id);
    }
    console.log(`Cleared ${storageFiles.length} storage files`);

    return null;
  },
});

