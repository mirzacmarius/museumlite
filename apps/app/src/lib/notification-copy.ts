export function getNotificationCopy(
  notification: NotificationCopySource,
  translate: NotificationTranslator,
): NotificationCopy {
  if (notification.type === "system_announcement") {
    return { title: notification.title, message: notification.message };
  }
  const titleMatch = getTitleMatch(notification.title);
  const messageMatch = getMessageMatch(notification.message);
  const localizeValues = (match: Match | null) => {
    if (!match?.values) return match?.values;
    const values = { ...match.values };
    if (typeof values.workflowType === "string") {
      const workflowTypes: Record<string, string> = {
        accession: "accession",
        deaccession: "deaccession",
        loan: "loan",
        exhibition: "exhibition",
        conservation: "conservation",
        move_request: "moveRequest",
        "move request": "moveRequest",
      };
      const workflowKey = workflowTypes[values.workflowType];
      if (workflowKey) {
        values.workflowType = translate(
          `untranslatedComponents.notificationCopy.workflowTypes.${workflowKey}`,
        );
      }
    }
    if (
      typeof values.job === "string" &&
      values.job.startsWith("__translated_job__")
    ) {
      values.job = translate(
        `untranslatedComponents.notificationCopy.jobTypes.${values.job.slice("__translated_job__".length)}`,
      );
    }
    if (typeof values.status === "string") {
      const statuses: Record<string, string> = {
        granted: "granted",
        denied: "denied",
      };
      const statusKey = statuses[values.status];
      if (statusKey) {
        values.status = translate(
          `untranslatedComponents.notificationCopy.statuses.${statusKey}`,
        );
      }
    }
    if (typeof values.direction === "string") {
      const directionKey =
        values.direction === "incoming" || values.direction === "outgoing"
          ? values.direction
          : undefined;
      if (directionKey) {
        values.direction = translate(
          `untranslatedComponents.notificationCopy.loanTypes.${directionKey}`,
        );
      }
    }
    return values;
  };
  return {
    title: titleMatch
      ? translate(
          `untranslatedComponents.${titleMatch.key}`,
          localizeValues(titleMatch),
        )
      : notification.title,
    message: messageMatch
      ? translate(
          `untranslatedComponents.${messageMatch.key}`,
          localizeValues(messageMatch),
        )
      : notification.message,
  };
}
