export type NotificationTranslator = (
  key: string,
  values?: Record<string, string | number>,
) => string;

export interface NotificationCopySource {
  title: string;
  message: string;
  type?: string;
}

export interface NotificationCopy {
  title: string;
  message: string;
}

type Match = { key: string; values?: Record<string, string | number> };

function matchTemplate(
  value: string,
  template: RegExp,
): RegExpExecArray | null {
  return template.exec(value);
}

